#!/usr/bin/env python3
"""Generates the README assets into ../assets (prefix v2-).

Edit the data below, then run:  python scripts/cinder_v2.py
Each asset is a self-contained dark panel, so it reads the same in GitHub's
light and dark themes. The portrait is embedded as base64 because GitHub
blocks external images inside SVGs.

Design rules: one serif for display, one sans for text, mono only for URLs.
The accent marks links and a short hairline under each heading, nothing else.
No glows, no kickers, no icon tiles.
"""
import base64
from pathlib import Path
from xml.sax.saxutils import escape as x

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets"
W = 1200

PAPER, RULE, RULE2 = "#100f0e", "#262321", "#3a3633"
INK, MUTE, EMBER = "#ece7e1", "#8f8881", "#f07a3a"
SERIF = "'Iowan Old Style','Palatino Linotype',Palatino,Georgia,serif"
SANS = "-apple-system,'Segoe UI',system-ui,Roboto,Helvetica,Arial,sans-serif"
MONO = "ui-monospace,'SF Mono','Cascadia Code',Consolas,monospace"

APPS = [
    ("popcalc", "PopCalc", "On Google Play",
     "A calculator for everyday sums, built in Flutter.",
     "Flutter · Dart"),
    ("zeropuff", "ZeroPuff", "Launching soon",
     "A private quit-smoking companion: a smoke-free clock, a two-minute",
     "breathing pause for cravings, daily check-ins and money saved.",
     "Flutter · Riverpod · Isar · Supabase"),
]

PROJECTS = [
    ("msnovo", "MsNovo", "AI marking assistant built at Noverse Inc.",
     "Marks written answers against a rubric and drafts feedback teachers edit.",
     "Next.js · TypeScript", "noverseinc.com"),
    ("chatterbox", "Chatterbox", "Real-time chat with rooms and presence.",
     "Messages arrive live, without reloads.",
     "Next.js · TypeScript · WebSockets", "chatterbox-space.vercel.app"),
    ("skyscout", "SkyScout", "Flight search on the Amadeus API.",
     "Live fares, filters and price charts for finding the cheapest day.",
     "Next.js · TypeScript · Recharts", "skyy-scout.vercel.app"),
    ("brainzap", "BrainZap", "Quizzes generated by AI, scored like a game.",
     "Pick a topic, get a fresh quiz, track progress, share sets.",
     "React · Firebase", "brain-zap-99226.web.app"),
]

TOOLKIT = [
    ("Web", "Next.js, React, TypeScript, Tailwind CSS, shadcn/ui, Zustand"),
    ("Mobile", "Flutter, Dart, Riverpod, Isar, Firebase"),
    ("Backend", "Node.js, Express, REST, GraphQL, Supabase, PostgreSQL, MongoDB"),
    ("Shipping", "Vercel, Azure, Docker, GitHub Actions, Stripe, n8n, Figma"),
]

LINKS = [
    ("portfolio", "ornobaadi.tech"),
    ("linkedin", "LinkedIn"),
    ("x", "X"),
    ("email", "Email"),
    ("whatsapp", "WhatsApp"),
]


def svg(w, h, body, label):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
            f'width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-label="{x(label)}">\n'
            f'{body}\n</svg>\n')


def panel(w, h):
    return (f'<rect width="{w}" height="{h}" rx="14" fill="{PAPER}"/>'
            f'<rect x=".5" y=".5" width="{w-1}" height="{h-1}" rx="13.5" fill="none" stroke="{RULE}"/>')


def t(xp, yp, s, size, fam=SANS, fill=INK, extra=""):
    return f'<text x="{xp}" y="{yp}" font-family="{fam}" font-size="{size}" fill="{fill}" {extra}>{x(s)}</text>'


def write(name, content):
    (OUT / f"v2-{name}.svg").write_text(content, encoding="utf-8")


def hero():
    img = base64.b64encode((OUT / "portrait.jpg").read_bytes()).decode()
    h = 520
    body = f'''{panel(W, h)}
<defs><clipPath id="ph"><rect x="836" y="40" width="324" height="440" rx="10"/></clipPath>
<filter id="tone"><feColorMatrix type="saturate" values="0.55"/></filter></defs>
<image x="770" y="40" width="440" height="440" preserveAspectRatio="xMidYMid slice" clip-path="url(#ph)" filter="url(#tone)" xlink:href="data:image/jpeg;base64,{img}" href="data:image/jpeg;base64,{img}"/>
{t(64, 92, "Abu Jafar Md. Fajlay Rabby", 20, SANS, MUTE)}
{t(58, 222, "Aadi", 150, SERIF)}
<line x1="64" y1="262" x2="124" y2="262" stroke="{EMBER}" stroke-width="2"/>
{t(64, 318, "Full stack engineer. I build web products in Next.js", 28, SANS)}
{t(64, 358, "and mobile apps in Flutter, and the APIs behind both.", 28, SANS)}
{t(64, 440, "Dhaka, Bangladesh", 20, SANS, MUTE)}
{t(64, 472, "Open to full-time and freelance work", 20, SANS, MUTE)}'''
    write("hero", svg(W, h, body, "Aadi, full stack engineer building web products in Next.js and mobile apps in Flutter. Dhaka."))


def title(slug, text):
    h = 110
    body = (f'{t(2, 62, text, 46, SERIF)}'
            f'<line x1="2" y1="92" x2="{W-2}" y2="92" stroke="{RULE}"/>'
            f'<line x1="2" y1="92" x2="62" y2="92" stroke="{EMBER}" stroke-width="2"/>')
    write(f"title-{slug}", svg(W, h, body, text))


def row(slug, name, status, lines, stack, url=None):
    h = 96 + 40 * len(lines) + 40
    body = panel(W, h) + t(48, 92, name, 50, SERIF)
    if status:
        body += t(48, 132, status, 19, SANS, MUTE)
    for i, ln in enumerate(lines):
        body += t(440, 76 + i * 36, ln, 23 if i == 0 else 21, SANS, INK if i == 0 else MUTE)
    yb = 76 + 36 * len(lines) + 20
    body += f'<line x1="440" y1="{yb-14}" x2="{W-48}" y2="{yb-14}" stroke="{RULE}"/>'
    body += t(440, yb + 20, stack, 18, SANS, MUTE)
    if url:
        body += t(W - 48, yb + 20, url + " ↗", 18, MONO, EMBER, 'text-anchor="end"')
    return svg(W, h, body, f"{name}. " + " ".join(lines))


def toolkit():
    h = 64 + 66 * len(TOOLKIT)
    s = panel(W, h)
    for i, (k, v) in enumerate(TOOLKIT):
        y = 70 + i * 66
        if i:
            s += f'<line x1="48" y1="{y-42}" x2="{W-48}" y2="{y-42}" stroke="{RULE}"/>'
        s += t(48, y, k, 26, SERIF) + t(300, y, v, 21, SANS, INK if k == "Mobile" else MUTE)
    write("toolkit", svg(W, h, s, "; ".join(f"{k}: {v}" for k, v in TOOLKIT)))


def link(slug, label):
    w = 30 + len(label) * 10 + 34
    h = 44
    body = (f'<rect x=".5" y=".5" width="{w-1}" height="{h-1}" rx="8" fill="{PAPER}" stroke="{RULE2}"/>'
            + t(18, 28, label, 16, SANS, INK) + t(w - 18, 28, "↗", 15, SANS, EMBER, 'text-anchor="end"'))
    write(f"link-{slug}", svg(w, h, body, label))


def footer():
    h = 200
    body = (panel(W, h) + t(W // 2, 104, "Have something to build?", 46, SERIF, INK, 'text-anchor="middle"')
            + t(W // 2, 148, "aadi4789@gmail.com · ornobaadi.tech", 19, SANS, MUTE, 'text-anchor="middle"'))
    write("footer", svg(W, h, body, "Have something to build? aadi4789@gmail.com, ornobaadi.tech"))


if __name__ == "__main__":
    hero()
    for slug, text in [("apps", "Apps on Google Play"), ("work", "Selected work"),
                       ("toolkit", "Toolkit"), ("activity", "Contributions")]:
        title(slug, text)
    for a in APPS:
        slug, name, status, *rest = a
        write(f"app-{slug}", row(slug, name, status, rest[:-1], rest[-1]))
    for slug, name, line, desc, stack, url in PROJECTS:
        write(f"work-{slug}", row(slug, name, None, [line, desc], stack, url))
    toolkit()
    for slug, label in LINKS:
        link(slug, label)
    footer()
    print("ok")
