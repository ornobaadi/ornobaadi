def svg(h, body, label, style=""):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
            f'width="{W}" height="{h}" viewBox="0 0 {W} {h}" role="img" aria-label="{x(label)}">\n'
            f'<style>@media (prefers-reduced-motion:reduce){{*{{animation:none!important}}}}{style}</style>\n'
            f'{body}\n</svg>\n')


def panel(h, glow=None):
    g = ""
    if glow:
        cx, cy = glow
        g = (f'<defs><radialGradient id="pg" cx="{cx}" cy="{cy}" r=".6">'
             f'<stop offset="0" stop-color="{EMBER}" stop-opacity=".09"/>'
             f'<stop offset="1" stop-color="{EMBER}" stop-opacity="0"/></radialGradient></defs>'
             f'<rect width="{W}" height="{h}" rx="16" fill="url(#pg)"/>')
    return (f'<rect width="{W}" height="{h}" rx="16" fill="{PAPER}"/>{g}'
            f'<rect x=".5" y=".5" width="{W-1}" height="{h-1}" rx="16" fill="none" stroke="{RULE}"/>')


def t(xp, yp, s, size, fam=SANS, fill=INK, extra=""):
    return f'<text x="{xp}" y="{yp}" font-family="{fam}" font-size="{size}" fill="{fill}" {extra}>{s}</text>'


def mono(xp, yp, s, fill=MUTE, size=12, extra=""):
    return t(xp, yp, x(s), size, MONO, fill, f'letter-spacing=".12em" {extra}')


def write(name, content):
    (OUT / f"cinder-{name}.svg").write_text(content, encoding="utf-8")


